function parseRawQuote([rawText, rawAuthor]: RawQuote): { text: string; author: string } {
  let text = rawText.trim();
  let author = (rawAuthor ?? '').trim();

  if (!author) {
    if (text.includes(' — ')) {
      const parts = text.split(' — ');
      author = parts.pop()?.trim() ?? '';
      text = parts.join(' — ').trim();
    } else if (text.includes(' , ')) {
      const parts = text.split(' , ');
      author = parts.pop()?.trim() ?? '';
      text = parts.join(' , ').trim();
    }
  }

  // Baştaki/sondaki tırnak işaretlerini temizle
  text = text.replace(/^["'“”]+|["'“”]+$/g, '').trim();
  author = author.replace(/^["'“”]+|["'“”]+$/g, '').trim();

  return { text, author: author || 'Anonim' };
}

export const QUOTES: readonly Quote[] = (Object.keys(RAW) as CategoryId[]).flatMap((categoryId) =>
  RAW[categoryId].map((raw, index) => {
    const { text, author } = parseRawQuote(raw);
    return {
      id: `${categoryId}-${index + 1}`,
      text,
      author,
      categoryId,
    };
  }),
);

const byId = new Map(QUOTES.map((q) => [q.id, q]));

export function getQuote(id: string): Quote | undefined {
  return byId.get(id);
}

export function getQuotesByCategories(ids: readonly CategoryId[]): Quote[] {
  const set = new Set(ids);
  return QUOTES.filter((q) => set.has(q.categoryId));
}
